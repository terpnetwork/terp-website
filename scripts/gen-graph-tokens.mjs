#!/usr/bin/env node
// public/graphs/graph-tokens.css: every theme token (custom properties only) from
// public/global.css, for the graph pages that cannot load the full stylesheet
// (it styles body, links and controls). One source of truth: edit global.css,
// then run this (build.js runs it too).
//   node scripts/gen-graph-tokens.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const site = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = fs.readFileSync(path.join(site, 'public/global.css'), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
const THEME_SEL = /^(?::root|html(?:\[data-(?:theme|tn-mode)(?:=["']?[\w-]+["']?)?\])*|\[data-(?:theme|tn-mode)(?:=["']?[\w-]+["']?)?\])$/;
const out = []; let i = 0, rules = 0, props = 0;
while (i < src.length) {
  const open = src.indexOf('{', i); if (open < 0) break;
  const sel = src.slice(i, open).trim();
  let depth = 1, j = open + 1;
  while (j < src.length && depth) { if (src[j] === '{') depth++; else if (src[j] === '}') depth--; j++; }
  const body = src.slice(open + 1, j - 1);
  i = j;
  if (sel.startsWith('@') || body.includes('{')) continue;
  const sels = sel.split(',').map((s) => s.trim().replace(/\s+/g, ' '));
  if (!sels.every((s) => THEME_SEL.test(s))) continue;
  const decls = body.split(';').map((d) => d.trim()).filter((d) => d.startsWith('--'));
  if (!decls.length) continue;
  rules++; props += decls.length;
  out.push(`${sels.join(',\n')} {\n${decls.map((d) => `  ${d.replace(/\s*\n\s*/g, ' ')};`).join('\n')}\n}`);
}
const css = `/* Generated by scripts/gen-graph-tokens.mjs from public/global.css. Do not edit. */\n${out.join('\n')}\n`;
const dest = path.join(site, 'public/graphs/graph-tokens.css');
if (process.argv.includes('--check')) { const cur = fs.existsSync(dest) ? fs.readFileSync(dest, 'utf8') : ''; if (cur !== css) { console.error('graph-tokens.css is stale'); process.exit(1); } }
else fs.writeFileSync(dest, css);
console.log(`graph-tokens.css: ${rules} rules, ${props} properties`);
